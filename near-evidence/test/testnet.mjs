import {connect,keyStores,KeyPair} from 'near-api-js';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {prepare,verify,readReceipt} from '../receipt.mjs';
const secret=JSON.parse(fs.readFileSync('../.secrets/near-hackathon-testnet.json'));
const ks=new keyStores.InMemoryKeyStore();await ks.setKey('testnet',secret.accountId,KeyPair.fromString(secret.privateKey));
const near=await connect({networkId:'testnet',nodeUrl:'https://rpc.testnet.near.org',keyStore:ks});
const account=await near.account(secret.accountId);
const p=spawnSync('python3',['-c',`import json,sys;sys.path.insert(0,'..');from app.scoring import qualify;print(json.dumps(qualify({'available_mw':20,'power_ready':True,'power_price':0.055,'intended_use':'both'})))`],{encoding:'utf8'});assert.equal(p.status,0);
const report=JSON.parse(p.stdout);const prepared=prepare(report,'41d099a75d1fca4962b5a5bab731e958125066d7');
fs.writeFileSync('build/qualification-envelope.private.json',JSON.stringify(prepared),{mode:0o600});
const call=(methodName,args)=>account.functionCall({contractId:secret.accountId,methodName,args,gas:30000000000000n,attachedDeposit:0n});
const anchor=await call('anchor',prepared.anchor);
const chain=await readReceipt({contract:secret.accountId,id:prepared.anchor.id});
assert.equal(verify(prepared.envelope,chain.receipt,secret.accountId,prepared.anchor.id).valid,true);
assert.equal(verify({...prepared.envelope,report:{...report,classification:'FORGED'}},chain.receipt,secret.accountId,prepared.anchor.id).valid,false);
await assert.rejects(call('anchor',prepared.anchor));
const revokedTx=await call('revoke',{id:prepared.anchor.id});
const revoked=await readReceipt({contract:secret.accountId,id:prepared.anchor.id});
assert.equal(verify(prepared.envelope,revoked.receipt,secret.accountId,prepared.anchor.id).valid,false);
fs.writeFileSync('build/qualification-testnet-proof.json',JSON.stringify({network:'NEAR TESTNET',fictional:true,accountId:secret.accountId,anchorTx:anchor.transaction.hash,revokeTx:revokedTx.transaction.hash,checks:['actual Python qualification committed','RPC final readback','tampered report rejected locally','duplicate rejected by contract','onchain revocation read back'],original:chain,revoked},null,2));
console.log('PASS: actual qualification / NEAR anchor / readback / tamper / duplicate / revoke');
